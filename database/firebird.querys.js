QUERY.GET_SUPPLIER_BY_ID = ( id ) => {
    return `
        SELECT 
        A.*,
        B.CLAVE_PROV
    FROM 
        PROVEEDORES A 
    LEFT JOIN 
        GET_CLAVE_PROV(A.PROVEEDOR_ID) B 
    ON 
        (B.PROVEEDOR_ID = A.PROVEEDOR_ID) 
    WHERE 
        A.PROVEEDOR_ID = ${ id }`;
} 

