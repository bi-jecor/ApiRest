QUERY.GET_JEC_ARTICULOS_PRECIOS = () => {
    return `
    SELECT
        C.CLAVE_ARTICULO,
        ROUND( PRECIO_LISTA, 4) AS  PRECIO_LISTA,
        ROUND( PRECIO_MAYOREO, 4) AS  PRECIO_MAYOREO,
        ROUND( PRECIO_ESPECIAL, 4) AS  PRECIO_ESPECIAL,
        ROUND( PRECIO_TIENDA, 4) AS  PRECIO_TIENDA,
        ROUND( PRECIO_TIENDA_JECOR, 4) AS  PRECIO_TIENDA_JECOR,
        ROUND( PRECIO_MINIMO, 4) AS  PRECIO_MINIMO,
        ROUND( PRECIO_CONSUMO_INTERNO, 4) AS  PRECIO_CONSUMO_INTERNO
    FROM P_GET_JEC_ART_PRICES P
    JOIN CLAVES_ARTICULOS C ON P.ARTICULO_ID = C.ARTICULO_ID
    WHERE C.ROL_CLAVE_ART_ID = 17
    `
}

