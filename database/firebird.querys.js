QUERY.GET_PENDING_RECEIPTS = `
    SELECT A.NOMBRE, D.FECHA, D.FOLIO, P.NOMBRE AS PROVEEDOR, D.IMPORTE_NETO, D.TOTAL_IMPUESTOS, (D.IMPORTE_NETO + D.TOTAL_IMPUESTOS) AS TOTAL
    FROM DOCTOS_CM D
    JOIN PROVEEDORES P ON P.PROVEEDOR_ID = D.PROVEEDOR_ID
    JOIN ALMACENES A ON A.ALMACEN_ID = D.ALMACEN_ID
    WHERE D.TIPO_DOCTO = 'R' AND D.ESTATUS = 'P' AND D.FECHA >= '01.01.2023'
    ORDER BY D.FECHA
`;

