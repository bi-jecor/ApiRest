QUERY.P_GET_JEC_ARTS_ULT_COST_FULL = ( DATE ) => {
    return `
    SELECT
     CA.CLAVE_ARTICULO,
        UC.COSTO_PROMEDIO
    FROM
        P_GET_JEC_ARTS_ULT_COST_FULL( '${ DATE }', 30 ) UC
    JOIN
        CLAVES_ARTICULOS CA
    ON
        UC.ARTICULO_ID = CA.ARTICULO_ID
    WHERE
        CA.ROL_CLAVE_ART_ID = 17
        AND UC.COSTO_PROMEDIO != 0
    `
}

